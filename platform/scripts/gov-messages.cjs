for (const [loc, obj] of [['en', en], ['ms', ms], ['ta', ta]]) {
  const p = path.join(__dirname, '..', 'messages', `${loc}.json`);
  let s = fs.readFileSync(p, 'utf8');
  if (JSON.parse(s).gov) {
    console.log(loc, 'already has gov; skipped');
    continue;
  }
  const eol = s.includes('\r\n') ? '\r\n' : '\n';
  const end = s.lastIndexOf('}');
  const body = JSON.stringify(obj, null, 2).split('\n').map((l) => '  ' + l).join(eol).replace(/^ {2}/, '');
  s = s.slice(0, end).replace(/\s+$/, '') + ',' + eol + '  "gov": ' + body + eol + '}' + eol;
  JSON.parse(s);
  fs.writeFileSync(p, s);
  console.log(loc, 'ok');
}
