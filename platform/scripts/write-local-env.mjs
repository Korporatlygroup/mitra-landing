// Writes platform/.env.local from the running local Supabase stack. Run from platform/: node scripts/write-local-env.mjs
// Local demo keys only. The file is gitignored.
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

let out;
try {
  out = execSync('npx supabase status -o env', { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
} catch {
  console.error('Could not read the local Supabase status. Is the stack running (npm run db:start)?');
  process.exit(1);
}

const vars = {};
for (const line of out.split(/\r?\n/)) {
  const m = line.match(/^([A-Z_]+)="?(.*?)"?$/);
  if (m) vars[m[1]] = m[2];
}

const need = ['API_URL', 'PUBLISHABLE_KEY', 'SECRET_KEY'];
const missing = need.filter((k) => !vars[k]);
if (missing.length) {
  console.error(`Supabase status did not report: ${missing.join(', ')}`);
  process.exit(1);
}

const env = [
  '# Generated by scripts/write-local-env.mjs. Local development only. Do not commit.',
  `NEXT_PUBLIC_SUPABASE_URL=${vars.API_URL}`,
  `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${vars.PUBLISHABLE_KEY}`,
  `SUPABASE_SECRET_KEY=${vars.SECRET_KEY}`,
  'SITE_URL=http://127.0.0.1:3000',
  'SMTP_URL=smtp://127.0.0.1:54425',
  'MAIL_FROM="MITRA <no-reply@mitra.local>"',
  `MAILPIT_URL=${vars.MAILPIT_URL || 'http://127.0.0.1:54424'}`,
  '',
].join('\n');

writeFileSync(join(root, '.env.local'), env, { mode: 0o600 });
console.log('Wrote .env.local (keys not printed).');
